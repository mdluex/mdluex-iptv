"""Refresh the built-in snapshot of the Mdluex Industries YouTube channel.

The app loads all of this live on the TV; the snapshot is the fallback when YouTube can't be
reached (and what the PC preview shows). Run:  python tools/update_channel.py
"""
import json, os, re, urllib.request, xml.etree.ElementTree as ET

CHANNEL_ID = "UCPS4VJgphh0fNQAbhU6eY7w"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "js", "channel_snapshot.js")
NS = {"a": "http://www.w3.org/2005/Atom", "yt": "http://www.youtube.com/xml/schemas/2015",
      "media": "http://search.yahoo.com/mrss/"}


def get(url):
    req = urllib.request.Request(url, headers={"Accept-Language": "en", "User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=20).read()


def feed(query):
    root = ET.fromstring(get("https://www.youtube.com/feeds/videos.xml?" + query))
    videos = []
    for e in root.findall("a:entry", NS):
        g = e.find("media:group", NS)
        videos.append({
            "id": e.findtext("yt:videoId", namespaces=NS),
            "title": e.findtext("a:title", namespaces=NS),
            "published": e.findtext("a:published", namespaces=NS),
            "desc": (g.findtext("media:description", namespaces=NS) or "")[:400] if g is not None else "",
        })
    return root.findtext("a:title", namespaces=NS), videos


name, uploads = feed("channel_id=" + CHANNEL_ID)
_, long_videos = feed("playlist_id=UULF" + CHANNEL_ID[2:])   # uploads, long videos only
_, shorts = feed("playlist_id=UUSH" + CHANNEL_ID[2:])        # uploads, Shorts only

featured = None
try:
    html = get(f"https://www.youtube.com/channel/{CHANNEL_ID}").decode("utf-8", "replace")
    m = re.search(r'"channelVideoPlayerRenderer":\{"videoId":"([\w-]{11})","title":\{"runs":\[\{"text":"((?:[^"\\]|\\.)*)"', html)
    if m:
        featured = {"id": m.group(1), "title": json.loads('"' + m.group(2) + '"')}
except Exception as e:
    print("featured video lookup failed:", e)

playlists = []
try:
    html = get(f"https://www.youtube.com/channel/{CHANNEL_ID}/playlists").decode("utf-8", "replace")
    for pid in dict.fromkeys(re.findall(r'"playlistId":"(PL[\w-]+)"', html)):
        try:
            title, vids = feed("playlist_id=" + pid)
            if vids:
                playlists.append({"id": pid, "title": title, "videos": vids})
        except Exception as e:
            print("playlist", pid, "failed:", e)
except Exception as e:
    print("playlists lookup failed:", e)

data = {"channelId": CHANNEL_ID, "name": name, "featured": featured, "videos": uploads,
        "longVideos": long_videos, "shorts": shorts, "playlists": playlists}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/update_channel.py - fallback copy of the channel. */\n")
    f.write("var CHANNEL_SNAPSHOT = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"'{name}': {len(uploads)} latest, {len(long_videos)} videos, {len(shorts)} shorts, "
      f"{len(playlists)} playlists ({', '.join(p['title'] for p in playlists)})")
